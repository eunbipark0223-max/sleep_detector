// stage_texts.dart — 단계별 문구 (경고 화면 · 운행 화면 · 홈 화면 · 음성 공통)
// ═══════════════════════════════════════════════════════════════
// 담당: 팀장   |   우선: P0 (11/11 UX 정리)
//
// [이 파일이 하는 일]
//   - 같은 단계에서 화면마다 말이 달랐던 것을 한 곳에 모은다 (기사는 어디서 보든 같은 말을 보고 듣는다)
//   - 말투: 경고(큰 글씨 · 음성)는 "-습니다" 로 짧고 단호하게, 그 밖의 안내는 "-어요"
//
// [쓰는 곳]
//   - headline : 경고 화면 큰 글씨 · 운행 화면 큰 글씨 · 홈 화면 상태 카드 (1 ~ 3단계)
//   - voice    : 경고 화면 시작 음성 (1 · 2단계) · 3단계 30초 반복 음성
//
// [주의]
//   - 문구를 바꿀 때는 여기 한 곳만 고친다 (화면 파일에 단계 문구를 직접 쓰지 않는다)
//   - 3단계는 시작할 때 고정 문구를 읽지 않는다 (기획안 8-7: 알람 → 기사 음성 보고). voice(3) 은 30초 반복에만 쓴다
// ═══════════════════════════════════════════════════════════════

class StageTexts {
  StageTexts._();

  /// 0단계 (정상)
  static const String normal = '안전 운전 중이에요';

  /// 화면 큰 글씨 (줄바꿈 포함). 0단계는 [normal]
  static String headline(int stage) {
    switch (stage) {
      case 1:
        return '졸음이 감지됐습니다.\n정신 차려 주세요';
      case 2:
        return '계속 졸고 있습니다.\n가까운 졸음쉼터에서 쉬어 주세요';
      case 3:
        return '관리자에게 알렸습니다.\n안전한 곳에 바로 정차해 주세요';
      default:
        return normal;
    }
  }

  /// 고개를 숙인 채 눈 뜸으로 취소됐을 때 한 번 (11/11 — 깨어 있으면 고개를 들게, 단계 변화 없음)
  static const String headDownGuide = '고개를 들고 앞을 봐 주세요';

  /// 음성으로 읽는 문장 (큰 글씨와 같은 말, 줄바꿈 없이)
  static String voice(int stage) => headline(stage).replaceAll('\n', ' ');
}
