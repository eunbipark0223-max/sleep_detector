# 담당: B (prep_eye) · A (crop_eye)   |   우선: P2 (USE_CNN 채택 시 P0)
# 수업 원본: (신규) 딥러닝 8·14차시 노트북의 이미지 전처리 부분
#
# [이 파일이 하는 일]
#   - 학습(Colab eye_cnn.ipynb)과 서버(face_service.py)가 **같은 함수**로 눈 사진을 만든다
#     → 전처리가 어긋나서 정확도가 떨어지는 일을 막음
#
#   [학습]  MRL 눈 사진(이미 눈만 잘림) ──────────→ prep_eye → CNN
#   [서버]  얼굴 사진 → crop_eye(MediaPipe 눈 점) → prep_eye → CNN
#
# [만들 것 (이름 약속 — 다른 파일이 이 이름으로 부름)]
#   - crop_eye(image, eye_points, pad=0.4) → 눈 부분 이미지 (numpy, BGR 또는 흑백)      … A, 서버만 씀
#       · eye_points: 한쪽 눈 점 6개의 픽셀 좌표 [(x, y), ...] (face_service 의 EAR 점과 같은 번호)
#       · 점들을 감싸는 상자 + 위아래 · 좌우 여유(pad 비율). MRL 처럼 눈이 가운데 오게, 가로세로 비슷하게
#       · 사진 밖으로 나가면 잘라서 맞춤, 너무 작으면(예: 8px 미만) None
#   - prep_eye(eye_img, size=64) → float32 배열 (size × size, 0~1)                     … B, 학습 · 서버 공용
#       · 흑백 변환(이미 흑백이면 그대로) → size × size 로 줄이기 → 0~1 정규화
#       · 정규화 방식은 이 함수 한 곳에서만 정한다 (노트북에서 따로 /255 하지 않기)
#
# [주의]
#   - cv2 · numpy 만 import (FastAPI · mediapipe · config 를 부르지 않음) → Colab 에 이 파일 하나만 올려서 씀
#   - size 는 인자로 받는다: 서버는 config.CNN_INPUT_SIZE, 노트북은 64 — 두 값은 항상 같아야 함
#   - 증강(밝기 · 회전 · 좌우 반전 등)은 여기에 넣지 않는다 → 학습할 때만, 노트북에서
#   - 이 파일을 고치면 Colab 에도 다시 올리고, 바꾼 내용을 A · B 둘 다 알아야 함
#   - Colab 사용: 왼쪽 파일 탭에 업로드 → from eye_preprocess import prep_eye
#
